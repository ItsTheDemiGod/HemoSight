"""Phase 9A: re-evaluate both arms as a SCREENING task, not a regression task.

Every gate in this project was written in mean absolute error, g/dL. The product a
screening tool delivers is a binary referral decision. This script evaluates that task
against the criteria pre-declared in CLAUDE.md section 6 (Phase 9A) and committed
before it ran.

Nothing is retrained except what was never saved: the cross-site image-CNN per-subject
predictions (Phase 6.5 wrote only summary MAE), regenerated by
`scripts/cross_site_cnn_predictions_phase9a.py` with the recorded construction. Baseline
per-subject predictions were likewise never saved and are regenerated here on the
IDENTICAL folds - KFold(10, shuffle=True, random_state=20260911) - using the same
estimators as Phase 4 Gate B and Phase 6.5 Task 2.

Outputs `data/interim/phase9a/screening.json`.
"""
