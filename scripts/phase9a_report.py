        """A cross-site rate with its interval attached, never bare (Phase 9E)."""
        d = xsci.get(direction, {}).get(metric)
        v = xs["directions"][direction]["cnn"][metric]
        if not d:
            return f(v, nd)
        return f"{f(v, nd)} {ci([d['lo'], d['hi']], nd)}"

