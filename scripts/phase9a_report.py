            k, f(ms["model_sensitivity"]), f(ms["baseline_sensitivity"]),
            signed(ms["sensitivity_difference"]), ci(ms["sensitivity_difference_ci"]),
            f(mn["model_specificity"]), f(mn["baseline_specificity"]),
